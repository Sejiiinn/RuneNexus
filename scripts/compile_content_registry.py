#!/usr/bin/env python3
"""Compile the Godot and server content registries (gem, turret and module identities) from content sources."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = 'server/internal/contentregistry/generated.go'
GODOT_TARGET = 'godot/content/generated_content_registry.gd'


def _strings(values) -> str:
    return '{' + ', '.join(json.dumps(value) for value in values) + '}'


def _range(limits) -> str:
    return '{' + f"{int(limits['min'])}, {int(limits['max'])}" + '}'


def _grade_ranges(grades, ranges) -> str:
    return '{' + ', '.join(f'{json.dumps(grade)}: {_range(ranges[grade])}' for grade in grades) + '}'


def _identities(root: Path) -> dict:
    growth = json.loads((root / 'godot/content/growth_content.json').read_text())
    turrets = list(json.loads((root / 'godot/content/source/turrets.json').read_text()))
    module = growth['module']
    if list(growth['turretRules']) != turrets or list(module['pools']) != turrets or list(module['families']) != turrets:
        raise ValueError('Turret identities differ between turrets.json and growth_content.json')
    parts = list(module['pools'][turrets[0]])
    grades = list(next(iter(module['ranges'].values())))
    for turret in turrets:
        if list(module['pools'][turret]) != parts or list(module['families'][turret]) != parts:
            raise ValueError(f'Module parts differ for {turret}')
    for option, ranges in [*module['ranges'].items(),
                           *(item for part in module.get('partRanges', {}).values() for item in part.items())]:
        if list(ranges) != grades:
            raise ValueError(f'Module grades differ for {option}')
    return {'growth': growth, 'module': module, 'turrets': turrets, 'parts': parts, 'grades': grades}


def generated_output(root: Path = ROOT) -> str:
    ids = _identities(root)
    growth, module, turrets, parts, grades = ids['growth'], ids['module'], ids['turrets'], ids['parts'], ids['grades']
    out = ['// Code generated by scripts/compile_content_registry.py; DO NOT EDIT.', 'package contentregistry', '']
    out.append('var gemTypes = [...]string' + _strings(growth['gems']))
    out.append('var turretTypes = [...]string' + _strings(turrets))
    out.append('var moduleParts = [...]string' + _strings(parts))
    out.append('var moduleGrades = [...]string' + _strings(grades))
    out += ['', 'var moduleFamilies = map[string]map[string]string{']
    for turret in turrets:
        families = module['families'][turret]
        out.append(f'\t{json.dumps(turret)}: {{' + ', '.join(f'{json.dumps(part)}: {json.dumps(families[part])}' for part in parts) + '},')
    out += ['}', '', 'var modulePools = map[string]map[string][]string{']
    for turret in turrets:
        out.append(f'\t{json.dumps(turret)}: {{')
        for part in parts:
            out.append(f'\t\t{json.dumps(part)}: {_strings(module["pools"][turret][part])},')
        out.append('\t},')
    out += ['}', '', 'var moduleRanges = map[string]map[string]Range{']
    for option, ranges in module['ranges'].items():
        out.append(f'\t{json.dumps(option)}: {_grade_ranges(grades, ranges)},')
    out += ['}', '', '// Part-specific ranges override moduleRanges for that part only.',
            'var modulePartRanges = map[string]map[string]map[string]Range{']
    for part, options in module.get('partRanges', {}).items():
        out.append(f'\t{json.dumps(part)}: {{')
        for option, ranges in options.items():
            out.append(f'\t\t{json.dumps(option)}: {_grade_ranges(grades, ranges)},')
        out.append('\t},')
    out.append('}')
    return '\n'.join(out) + '\n'


def generated_godot_output(root: Path = ROOT) -> str:
    ids = _identities(root)
    families = [ids['module']['families'][turret][part] for turret in ids['turrets'] for part in ids['parts']]
    out = ['extends RefCounted',
           '# Generated by scripts/compile_content_registry.py; edit growth_content.json or source/turrets.json.']
    for name, values in [('GEM_TYPES', ids['growth']['gems']), ('TURRET_TYPES', ids['turrets']),
                         ('MODULE_PARTS', ids['parts']), ('MODULE_GRADES', ids['grades']),
                         ('MODULE_FAMILIES', families), ('MODULE_OPTION_TYPES', list(ids['module']['ranges']))]:
        out.append(f'const {name} := ' + json.dumps(values, separators=(',', ':')))
    return '\n'.join(out) + '\n'


def compile_registry(root: Path = ROOT, check: bool = False) -> None:
    for relative, expected in [(TARGET, generated_output(root)), (GODOT_TARGET, generated_godot_output(root))]:
        target = root / relative
        if check:
            if not target.exists() or target.read_text() != expected:
                raise ValueError('Stale content registry; run scripts/compile_content_registry.py')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    compile_registry(args.root, args.check)
