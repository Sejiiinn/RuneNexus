#!/usr/bin/env python3
"""Compile server gem capability rules from the client content sources."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated_output(root: Path = ROOT) -> str:
    requirements = json.loads((root / 'godot/content/gem_capabilities.json').read_text())['gemRequirements']
    turrets = json.loads((root / 'godot/content/source/turrets.json').read_text())
    capabilities = {key: turret['configuration']['statInput']['definition'].get('attackCapabilities', [])
                    for key, turret in turrets.items()}
    output = '// Code generated by scripts/compile_gem_capabilities.py; DO NOT EDIT.\npackage gemcapabilities\n\n'
    for name, values in [('requirements', requirements), ('capabilities', capabilities)]:
        output += f'var {name} = map[string][]string{{\n'
        for key, entries in sorted(values.items()):
            output += '\t' + json.dumps(key) + ': {' + ', '.join(json.dumps(entry) for entry in entries) + '},\n'
        output += '}\n\n'
    return output + '''// Allows evaluates capability-based gems. Other gems retain their legacy rules.
func Allows(turret, gem string) (applies, allowed bool) {
	required, applies := requirements[gem]
	if !applies {
		return false, false
	}
	available, exists := capabilities[turret]
	if !exists {
		return true, false
	}
	for _, requirement := range required {
		found := false
		for _, capability := range available {
			if capability == requirement {
				found = true
				break
			}
		}
		if !found {
			return true, false
		}
	}
	return true, true
}
'''


def compile_capabilities(root: Path = ROOT, check: bool = False) -> None:
    # Tower tags are authored once; the client growth projection follows them.
    source = json.loads((root / 'godot/content/source/turrets.json').read_text())
    growth_path = root / 'godot/content/growth_content.json'
    growth = json.loads(growth_path.read_text())
    changed = False
    for key, turret in source.items():
        expected_tags = turret['configuration']['statInput']['definition'].get('attackCapabilities', [])
        rule = growth['turretRules'].setdefault(key, {})
        if rule.get('attackCapabilities') != expected_tags:
            if check:
                raise ValueError(f'Stale growth capability projection: {key}')
            rule['attackCapabilities'] = expected_tags
            changed = True
    if changed:
        growth_path.write_text(json.dumps(growth, ensure_ascii=False, indent=2) + '\n')
    target = root / 'server/internal/gemcapabilities/generated.go'
    expected = generated_output(root)
    if check:
        if not target.exists() or target.read_text() != expected:
            raise ValueError('Stale gem capabilities; run scripts/compile_gem_capabilities.py')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    compile_capabilities(args.root, args.check)
